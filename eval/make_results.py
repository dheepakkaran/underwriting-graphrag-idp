"""Build RESULTS.md from results/*.json only (no hand-typed numbers)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = lambda n: json.loads((ROOT / "results" / n).read_text())
base, tri, trd = R("baseline_rules.json"), R("triage_test.json"), R("triage_dev.json")
ext, ext_t = R("extract_v2_all.json"), R("extract_v2_test_only.json")
ragt, ragd = R("rag_vs_graphrag_test.json"), R("rag_vs_graphrag_dev.json")
ledger = [json.loads(l) for l in (ROOT / "results/cost_ledger.jsonl").read_text().splitlines()]
usd, calls = sum(x["usd"] for x in ledger), len(ledger)
split = json.loads((ROOT / "data/split.json").read_text())
a, b = tri["agent"], tri["rules_baseline"]
pct = lambda x: f"{100 * x:.1f}%"

md = f"""# RESULTS (generated by `eval/make_results.py` from `results/*.json`)

Synthetic data only: 60 fictional submissions (28 with planted risk), test split = {len(split['test'])} files, frozen
before any LLM run (hash `{split['test_sha256_16']}`). Model: Claude Haiku 5.5 (`claude-haiku-5-5`), effort low.
Dev was used for prompt / agent changes; **test was run once** per component.

## 1 · Intelligent document processing (LLM extraction, prompt v2)
| | test | all 60 |
|---|---|---|
| key fields exactly right | {ext_t['test_fields']} fields, **{pct(ext_t['test_field_accuracy'])}** | {pct(ext['field_accuracy'])} |
| flag quotes found verbatim in the documents | {ext_t['test_quotes_verbatim']} | |
| seconds per file (3 PDFs) | | {ext['seconds_per_file']} |
Rules baseline (regex for the two known forms): test field accuracy {pct(base['test']['field_accuracy'])}.

## 2 · Routing: standard review vs refer to a senior underwriter (test, {a['n']} files, {a['risky']} risky)
| | rules baseline (no LLM) | LLM extraction + validators + agent |
|---|---|---|
| risky files caught (recall) | {b['missed'] and f"{a['risky'] - b['missed']}/{b['risky']}"} = {pct(b['recall'])} | {a['risky'] - a['missed']}/{a['risky']} = **{pct(a['recall'])}** |
| refer precision | {pct(b['precision'])} | {pct(a['precision'])} ({a['false_refers']} false refer) |
| route accuracy | {pct(b['accuracy'])} | {pct(a['accuracy'])} |
| broker/address ring files caught | {b['ring_caught']}/{b['ring_files']} | **{a['ring_caught']}/{a['ring_files']}** |
| injected-instruction files sent to standard | {b['injected_routed_standard']}/{b['injected_files']} | {a['injected_routed_standard']}/{a['injected_files']} |
| "decline" routes | 0 (no such route) | {tri['decline_routes']} |
Dev (20 files, after 3 agent iterations): recall {pct(trd['agent']['recall'])}, precision {pct(trd['agent']['precision'])}, rings {trd['agent']['ring_caught']}/{trd['agent']['ring_files']}.
Every referred file stops at a LangGraph `interrupt()` and waits in the human review queue (`/queue`).

## 3 · Cross-file questions: vector RAG vs GraphRAG-style graph retrieval (same model, same answer prompt)
| split | questions | vector RAG (bge-small, top-{ragt['top_k']}) | graph retrieval | difference (95% paired bootstrap CI) |
|---|---|---|---|---|
| test | {ragt['n']} | {ragt['vector_correct']}/{ragt['n']} = {pct(ragt['vector_acc'])} | {ragt['graph_correct']}/{ragt['n']} = **{pct(ragt['graph_acc'])}** | +{100 * ragt['diff_graph_minus_vector']:.0f} pts [{100 * ragt['ci95'][0]:+.0f}, {100 * ragt['ci95'][1]:+.0f}] |
| dev | {ragd['n']} | {ragd['vector_correct']}/{ragd['n']} | {ragd['graph_correct']}/{ragd['n']} | |
By type (test): {', '.join(f"{k} vector {v['vector']}/{v['n']} vs graph {v['graph']}/{v['n']}" for k, v in ragt['by_type'].items())}.

## 4 · Cost
All LLM calls in the project, dev iterations included: **{calls} calls, ${usd:.3f}** (hard cap $0.50, `results/cost_ledger.jsonl`).

See `FAILURES.md` for what went wrong and what was changed.
"""
(ROOT / "RESULTS.md").write_text(md)
print(md)
